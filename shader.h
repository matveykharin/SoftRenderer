// shader.h
// ---------------------------------------------------------------------------
// Интерфейс шейдера — так же, как на слайде «Shaders. Interface».
// Конвейер вызывает:
//   1) vertex()   — по одному разу для каждой из 3 вершин треугольника.
//      Должен вернуть координаты вершины в clip space (после Projection),
//      и может сохранить в себе «varying»-данные (нормаль, uv, ...),
//      которые потом будут интерполироваться по треугольнику.
//   2) fragment() — для каждого пикселя внутри треугольника.
//      Получает барицентрические координаты пикселя (веса трёх вершин),
//      вычисляет цвет. Возврат true = «отбросить пиксель» (discard).
// ---------------------------------------------------------------------------
#pragma once
#include "geometry.h"
#include "tgaimage.h"

struct IShader {
    virtual ~IShader() {}
    virtual Vec4f vertex(int iface, int nthvert) = 0;
    virtual bool  fragment(const Vec3f& bar, TGAColor& color) = 0;
};
